"""
Unified Keyword Generator for Ad Scraping Filters.

Generates positive (required) and negative (exclusion) keywords using Claude Sonnet
for filtering relevant ads during scraping.
"""

import json
from typing import Dict, List, Optional, Any

from . import api_keys
from . import config
from .rate_limiter import anthropic_limiter


def generate_keywords_with_sonnet(
    search_term: str,
    max_positive: int = 2,
    max_negative: int = 5
) -> Dict:
    """
    Use Claude Sonnet to generate smart filtering keywords.
    
    Args:
        search_term: The search query (e.g., "exterior painting")
        max_positive: Maximum positive keywords to generate (default 2)
        max_negative: Maximum negative keywords to generate (default 5)
    
    Returns:
        {
            'positive': ['keyword1', 'keyword2'],
            'negative': ['keyword1', 'keyword2', ...],
            'reasoning': 'Explanation of choices'
        }
    """
    # Initialize client if needed
    if not api_keys.ANTHROPIC_CLIENT:
        api_keys.initialize_clients()
    
    if not api_keys.ANTHROPIC_CLIENT:
        print("[WARNING] Claude not available, using fallback keywords")
        return _get_fallback_keywords(search_term, max_positive, max_negative)
    
    prompt = config.AI_PROMPTS['keyword_generation'].format(
        search_term=search_term,
        max_positive=max_positive,
        max_negative=max_negative
    )

    try:
        anthropic_limiter.wait()
        response = api_keys.ANTHROPIC_CLIENT.messages.create(
            model="claude-sonnet-4-20250514",
            max_tokens=300,
            messages=[{"role": "user", "content": prompt}]
        )
        
        # Safely extract text from response
        if response.content and len(response.content) > 0:
            content_block = response.content[0]
            if hasattr(content_block, 'text'):
                content = content_block.text.strip()
            else:
                content = str(content_block).strip()
        else:
            content = ""
        
        # Parse JSON from response
        if "```" in content:
            # Extract JSON from code block
            content = content.split("```")[1]
            if content.startswith("json"):
                content = content[4:]
            content = content.strip()
        
        result = json.loads(content)
        
        # Ensure we have the required keys
        if 'positive' not in result or 'negative' not in result:
            raise ValueError("Missing required keys in response")
        
        # Enforce limits
        result['positive'] = [k.lower().strip() for k in result['positive'][:max_positive]]
        result['negative'] = [k.lower().strip() for k in result['negative'][:max_negative]]
        
        if 'reasoning' not in result:
            result['reasoning'] = "Generated by Claude Sonnet"
        
        return result
        
    except Exception as e:
        print(f"[WARNING] Keyword generation failed: {e}")
        return _get_fallback_keywords(search_term, max_positive, max_negative)


def _get_fallback_keywords(search_term: str, max_positive: int, max_negative: int) -> Dict[str, Any]:
    """
    Generate fallback keywords when Claude is unavailable.
    
    Uses the search term words as positive keywords and common
    false-positive patterns as negative keywords.
    """
    # Extract meaningful words from search term
    words = [w.lower() for w in search_term.split() if len(w) > 2]
    positive = words[:max_positive] if words else [search_term.lower()]
    
    # Common false positive patterns - prioritized by frequency
    default_negative = [
        # Real estate (common false positive for home services)
        "property", "investment", "for sale", "cottage", "buy house",
        # Jobs/Employment
        "jobs", "hiring", "employment", "career",
        # Romance novels (huge polluter on Facebook)
        "novel", "story", "romance", "werewolf", "read now",
        # Other services
        "cleaning", "automotive", "car sales",
        # Religious
        "church", "sermon", "pastor",
        # Art (not home painting)
        "gallery", "exhibition", "art collection",
        # Games/Apps
        "game", "download", "install"
    ]
    
    return {
        'positive': positive,
        'negative': default_negative[:max_negative],
        'reasoning': "Fallback keywords (Claude unavailable)"
    }


def prompt_user_for_keywords(
    generated_keywords: Dict,
    allow_edit: bool = True
) -> Optional[Dict]:
    """
    Display generated keywords and get user approval.
    
    Args:
        generated_keywords: Dict with 'positive', 'negative', 'reasoning' keys
        allow_edit: Whether to allow user to edit the keywords
    
    Returns:
        Approved (and possibly edited) keywords dict
    """
    print("\n" + "=" * 50)
    print("  GENERATED FILTER KEYWORDS")
    print("=" * 50)
    
    print(f"\nPositive (required): {', '.join(generated_keywords['positive'])}")
    print(f"Negative (excluded): {', '.join(generated_keywords['negative'])}")
    print(f"\nReasoning: {generated_keywords.get('reasoning', 'N/A')}")
    
    if not allow_edit:
        return generated_keywords
    
    print("\nOptions:")
    print("  [Enter] Accept these keywords")
    print("  [p]     Edit positive keywords")
    print("  [n]     Edit negative keywords")
    print("  [r]     Regenerate keywords")
    
    while True:
        choice = input("\nYour choice: ").strip().lower()
        
        if choice == "" or choice == "y" or choice == "yes":
            print("[OK] Keywords accepted")
            return generated_keywords
        
        elif choice == "p":
            new_positive = input("Enter positive keywords (comma-separated, max 2): ").strip()
            if new_positive:
                keywords = [k.strip().lower() for k in new_positive.split(",")][:2]
                generated_keywords['positive'] = keywords
                print(f"[OK] Positive keywords updated: {', '.join(keywords)}")
        
        elif choice == "n":
            new_negative = input("Enter negative keywords (comma-separated, max 5): ").strip()
            if new_negative:
                keywords = [k.strip().lower() for k in new_negative.split(",")][:5]
                generated_keywords['negative'] = keywords
                print(f"[OK] Negative keywords updated: {', '.join(keywords)}")
        
        elif choice == "r":
            print("[INFO] Regenerating keywords...")
            return {'positive': [], 'negative': [], 'reasoning': 'Regenerate requested'}  # Signal to caller to regenerate
        
        else:
            print("[ERROR] Invalid choice. Press Enter to accept, 'p' to edit positive, 'n' to edit negative, 'r' to regenerate.")


